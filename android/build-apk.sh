#!/usr/bin/env bash
# ============================================================================
# ChainIt Android — reproducible release build (no Gradle, no Android Studio)
#
#   ./android/build-apk.sh
#
# Produces releases/ChainIt-Android.apk: compiled, 4-byte aligned and signed with
# the committed release key so every new build REPLACES the installed one in place
# (same package name + same certificate + higher versionCode).
#
# Toolchain (override with CHAINIT_TOOLCHAIN=/path):
#   $TC/aapt2                       resource compiler/linker
#   $TC/android.jar                 API 34 platform stubs
#   $TC/kotlinc/bin/kotlinc         Kotlin compiler
#   $TC/dx.jar                      .class -> classes.dex
#   $TC/apksigner.jar               APK Signature Scheme v2/v3 signer
#   $TC/py/jdk4py/java-runtime/bin  java / keytool
#
# IMPORTANT — the crash fix:
#   Kotlin >= 2.2 compiles lambdas to invokedynamic (LambdaMetafactory) by default.
#   The dx dexer cannot translate InvokeCustom bytecode, and the resulting APK dies
#   instantly at launch ("ChainIt Sibling keeps stopping"). We therefore force
#   -Xlambdas=class -Xsam-conversions=class so every lambda becomes a plain
#   anonymous class, and the script *verifies* that no LambdaMetafactory reference
#   survives into classes.dex before signing.
# ============================================================================
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TC="${CHAINIT_TOOLCHAIN:-/tmp/toolchain}"
JAVA_HOME_DIR="$TC/py/jdk4py/java-runtime"
export PATH="$JAVA_HOME_DIR/bin:$PATH"
JAVA="$JAVA_HOME_DIR/bin/java"
AAPT2="$TC/aapt2"
ANDROID_JAR="$TC/android.jar"
KOTLINC="$TC/kotlinc/bin/kotlinc"
DX="$TC/dx.jar"
APKSIGNER="$TC/apksigner.jar"

SRC="$REPO/android/app/src/main"
OUT="${CHAINIT_BUILD_DIR:-/tmp/chainit-apk-build}"
KEYSTORE="$REPO/android/keystore/chainit-release.p12"
KEYPROPS="$REPO/android/keystore/keystore.properties"
FINAL_APK="$REPO/releases/ChainIt-Android.apk"

[ -x "$AAPT2" ]    || { echo "missing aapt2 at $AAPT2"; exit 1; }
[ -f "$ANDROID_JAR" ] || { echo "missing android.jar at $ANDROID_JAR"; exit 1; }
[ -x "$KOTLINC" ]  || { echo "missing kotlinc at $KOTLINC"; exit 1; }
[ -f "$DX" ]       || { echo "missing dx.jar at $DX"; exit 1; }
[ -f "$APKSIGNER" ]|| { echo "missing apksigner.jar at $APKSIGNER"; exit 1; }
[ -f "$KEYSTORE" ] || { echo "missing release keystore at $KEYSTORE — never regenerate it"; exit 1; }

VERSION_CODE="$(sed -n 's/.*android:versionCode="\([0-9]*\)".*/\1/p' "$SRC/AndroidManifest.xml" | head -1)"
VERSION_NAME="$(sed -n 's/.*android:versionName="\([^"]*\)".*/\1/p' "$SRC/AndroidManifest.xml" | head -1)"
PKG="$(sed -n 's/.*package="\([^"]*\)".*/\1/p' "$SRC/AndroidManifest.xml" | head -1)"
echo "==> ChainIt Android $VERSION_NAME (versionCode $VERSION_CODE) — $PKG"

rm -rf "$OUT"
mkdir -p "$OUT/compiled_res" "$OUT/gen" "$OUT/classes" "$OUT/dex"

# ---------------------------------------------------------------- resources
echo "==> aapt2 compile"
"$AAPT2" compile --dir "$SRC/res" -o "$OUT/res.zip"
echo "==> aapt2 link (+ generate R.java)"
"$AAPT2" link \
  -o "$OUT/linked.apk" \
  --manifest "$SRC/AndroidManifest.xml" \
  -I "$ANDROID_JAR" \
  --java "$OUT/gen" \
  --min-sdk-version 26 \
  --target-sdk-version 34 \
  --version-code "$VERSION_CODE" \
  --version-name "$VERSION_NAME" \
  --auto-add-overlay \
  "$OUT/res.zip"

# ------------------------------------------------- R.java -> R.kt (no javac)
echo "==> generating R.kt from aapt2 R.java"
python3 - "$OUT/gen" "$PKG" <<'PY'
import os, re, sys
gen, pkg = sys.argv[1], sys.argv[2]
rjava = os.path.join(gen, pkg.replace('.', '/'), 'R.java')
text = open(rjava, encoding='utf-8').read()

out = [f"package {pkg}", "", "/** Generated by android/build-apk.sh from aapt2's R.java. Do not edit. */", "object R {"]
current = None
for raw in text.splitlines():
    line = raw.strip()
    m = re.match(r'public static final class\s+(\w+)\s*\{', line)
    if m:
        current = m.group(1)
        out.append(f"    object {current} {{")
        continue
    if line == '}' and current:
        out.append("    }")
        current = None
        continue
    if current:
        m = re.match(r'public static final int\s+(\w+)\s*=\s*(0x[0-9a-fA-F]+|-?\d+)\s*;', line)
        if m:
            out.append(f"        const val {m.group(1)}: Int = {m.group(2)}")
            continue
        m = re.match(r'public static final int\[\]\s+(\w+)\s*=\s*\{(.*)\}\s*;', line)
        if m:
            vals = m.group(2).replace(' ', '')
            out.append(f"        @JvmField val {m.group(1)}: IntArray = intArrayOf({vals})")
out.append("}")
kdir = os.path.join(gen, pkg.replace('.', '/'))
open(os.path.join(kdir, 'R.kt'), 'w', encoding='utf-8').write("\n".join(out) + "\n")
os.remove(rjava)
print("    R.kt written")
PY

# ------------------------------------------------------------------- kotlin
echo "==> kotlinc (-Xlambdas=class -Xsam-conversions=class)"
mapfile -t KT_SOURCES < <(find "$SRC/java" "$OUT/gen" -name '*.kt' | sort)
"$KOTLINC" \
  -jvm-target 1.8 \
  -Xlambdas=class \
  -Xsam-conversions=class \
  -nowarn \
  -classpath "$ANDROID_JAR" \
  -d "$OUT/classes" \
  "${KT_SOURCES[@]}"

# ------------------------------------------------------- runtime kotlin jars
echo "==> assembling runtime classpath (kotlin-stdlib, annotations)"
python3 - "$OUT" "$TC/kotlinc/lib" <<'PY'
import os, sys, zipfile
out, lib = sys.argv[1], sys.argv[2]
keep_roots = ('kotlin/', 'org/jetbrains/annotations/')
dst = os.path.join(out, 'runtime-libs.jar')
count = 0
with zipfile.ZipFile(dst, 'w', zipfile.ZIP_DEFLATED) as zf:
    for jar in ('kotlin-stdlib.jar', 'annotations-13.0.jar'):
        path = os.path.join(lib, jar)
        if not os.path.exists(path):
            print(f"    (skip missing {jar})")
            continue
        with zipfile.ZipFile(path) as src:
            for n in src.namelist():
                if not n.endswith('.class'):
                    continue
                # Multi-release classes and module descriptors break the dx dexer.
                if n.startswith('META-INF/') or 'module-info' in n:
                    continue
                if not n.startswith(keep_roots):
                    continue
                zf.writestr(n, src.read(n))
                count += 1
print(f"    runtime-libs.jar: {count} classes")
PY

# ---------------------------------------------------------------------- dex
echo "==> dx --dex"
"$JAVA" -Xmx2g -jar "$DX" --dex \
  --min-sdk-version=26 \
  --output="$OUT/dex/classes.dex" \
  "$OUT/classes" \
  "$OUT/runtime-libs.jar"

# --- HARD GUARD: invokedynamic must never reach the device ------------------
# Kotlin >= 2.2 compiles lambdas to invokedynamic by default. dx cannot encode InvokeCustom in the
# DEX v038 container that minSdk 26 requires, so such a class dies the moment ART touches it —
# the user-visible symptom is "ChainIt Sibling keeps stopping" on every launch. The flags above
# prevent it; this verifier proves it by walking real constant pools.
python3 "$REPO/android/tools/verify_dex_safety.py" \
  "$OUT/classes" "$OUT/runtime-libs.jar" "$OUT/indy-emulated-methods.txt" "$SRC/java"

# ------------------------------------------------------------- package APK
echo "==> packaging + 4-byte alignment"
python3 - "$OUT" <<'PY'
import os, struct, sys, zipfile, zlib
out = sys.argv[1]
linked = os.path.join(out, 'linked.apk')
dex = os.path.join(out, 'dex', 'classes.dex')
target = os.path.join(out, 'unsigned.apk')

def entries():
    with zipfile.ZipFile(linked) as z:
        for info in z.infolist():
            yield info.filename, z.read(info.filename)

base = []
arsc = None
for name, data in entries():
    if name == 'resources.arsc':
        arsc = (name, data)
    else:
        base.append((name, data))
if arsc is None:
    raise SystemExit('resources.arsc missing from aapt2 output')

dex_data = open(dex, 'rb').read()

def crc32(b): return zlib.crc32(b) & 0xFFFFFFFF

buf = bytearray()
central = []

def write_entry(name, data, stored, align):
    nb = name.encode('utf-8')
    extra = b''
    method = 0 if stored else 8
    payload = data if stored else zlib.compress(data, 9)[2:-4]
    header_len = 30 + len(nb) + len(extra)
    if align > 1 and stored:
        pad = (align - ((len(buf) + header_len) % align)) % align
        if pad:
            # Well-formed TLV padding field (tag 0xd935), as zipalign emits.
            extra = struct.pack('<HH', 0xd935, pad) + b'\x00' * pad
    offset = len(buf)
    buf.extend(struct.pack('<IHHHHHIIIHH',
                           0x04034b50, 20, 0, method, 0, 0x21,
                           crc32(data), len(payload), len(data), len(nb), len(extra)))
    buf.extend(nb)
    buf.extend(extra)
    buf.extend(payload)
    central.append((name, nb, method, crc32(data), len(payload), len(data), offset, extra))

# resources.arsc must be STORED and 4-byte aligned (Android 11+ requirement).
write_entry(arsc[0], arsc[1], True, 4)
data_off = 30 + len(arsc[0].encode()) + len(central[0][7])
assert data_off % 4 == 0, f'resources.arsc not aligned: {data_off}'
write_entry('classes.dex', dex_data, False, 1)
for name, data in base:
    stored = name.endswith(('.png', '.jpg', '.webp', '.arsc'))
    write_entry(name, data, stored, 4 if stored else 1)

cd_start = len(buf)
for name, nb, method, crc, csize, usize, offset, extra in central:
    buf.extend(struct.pack('<IHHHHHHIIIHHHHHII',
                           0x02014b50, 20, 20, 0, method, 0, 0x21,
                           crc, csize, usize, len(nb), len(extra), 0, 0, 0, 0, offset))
    buf.extend(nb)
    buf.extend(extra)
cd_size = len(buf) - cd_start
buf.extend(struct.pack('<IHHHHIIH', 0x06054b50, 0, 0, len(central), len(central), cd_size, cd_start, 0))
open(target, 'wb').write(bytes(buf))
print(f"    unsigned.apk: {len(buf)} bytes, {len(central)} entries, resources.arsc stored+aligned")
PY

# ------------------------------------------------------------------- signing
STOREPASS="$(sed -n 's/^storePassword=//p' "$KEYPROPS")"
KEYPASS="$(sed -n 's/^keyPassword=//p' "$KEYPROPS")"
ALIAS="$(sed -n 's/^keyAlias=//p' "$KEYPROPS")"

echo "==> apksigner (v2 + v3) with the committed release key"
"$JAVA" -jar "$APKSIGNER" sign \
  --ks "$KEYSTORE" \
  --ks-key-alias "$ALIAS" \
  --ks-pass "pass:$STOREPASS" \
  --key-pass "pass:$KEYPASS" \
  --v1-signing-enabled false \
  --v2-signing-enabled true \
  --v3-signing-enabled true \
  --v4-signing-enabled false \
  --out "$FINAL_APK" \
  "$OUT/unsigned.apk"

# ------------------------------------------------------------------ verify
echo "==> verifying"
# The phone must never hand its own UI to a browser again: no ACTION_VIEW jump to the PC's web UI.
#
# The `path:line:` prefix that grep -rn adds used to defeat the comment filter below, so this guard
# failed on the KDoc that *documents* the removed browser jump. Strip the prefix first, then drop
# comment lines, so only live code is judged - the guard still fails on any real ACTION_VIEW to :4173.
BROWSER_JUMP="$(grep -rn 'ACTION_VIEW' "$SRC/java" \
  | grep -v 'PcBrowserActivity.kt:.*content://' \
  | sed -E 's/^[^:]+:[0-9]+://' \
  | grep -vE '^[[:space:]]*(\*|//|/\*)' \
  | grep '4173' || true)"
if [ -n "$BROWSER_JUMP" ]; then
  echo "FATAL: an Android source still opens http://<pc>:4173 in a browser. Use PcBrowserActivity." >&2
  echo "$BROWSER_JUMP" >&2
  exit 1
fi
"$JAVA" -jar "$APKSIGNER" verify --verbose "$FINAL_APK" | sed 's/^/    /'
"$AAPT2" dump badging "$FINAL_APK" | grep -E "^package|^application-label|uses-permission: name='android.permission.BLUETOOTH" | sed 's/^/    /'
python3 - "$FINAL_APK" <<'PY'
import sys, zipfile
z = zipfile.ZipFile(sys.argv[1])
names = z.namelist()
assert 'classes.dex' in names, 'classes.dex missing'
assert 'resources.arsc' in names, 'resources.arsc missing'
info = z.getinfo('resources.arsc')
assert info.compress_type == zipfile.ZIP_STORED, 'resources.arsc must be stored'
dex = z.read('classes.dex')
for cls in (b'Lcom/chainit/android/ChainItApp;',
            b'Lcom/chainit/android/ui/MainActivity;',
            b'Lcom/chainit/android/ui/PcBrowserActivity;',
            b'Lcom/chainit/android/ui/Ds;',
            b'Lcom/chainit/android/net/PcVfsClient;',
            b'Lcom/chainit/android/net/ChainItFileProvider;',
            b'Lcom/chainit/android/service/SiblingDaemonService;',
            b'Lcom/chainit/android/net/BluetoothRfcommTransport;',
            b'Lcom/chainit/android/update/UpdateManager;',
            b'Lcom/chainit/android/update/UpdateFileProvider;'):
    assert cls in dex, f'{cls.decode()} missing from classes.dex'
print(f"    ✓ classes.dex {len(dex)} bytes, all ChainIt classes present (invokedynamic-free app code)")
print(f"    ✓ {len(names)} entries: {', '.join(sorted(n for n in names if not n.startswith('META-INF')))}")
PY
echo "==> OK  $FINAL_APK ($(stat -c%s "$FINAL_APK") bytes)"
echo "    Signing cert: $("$JAVA" -jar "$APKSIGNER" verify --print-certs "$FINAL_APK" 2>/dev/null | grep -m1 'SHA-256 digest' || true)"
